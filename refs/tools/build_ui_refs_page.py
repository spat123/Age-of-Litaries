def data_uri(path, width, q=70):
    im = Image.open(path).convert("RGB")
    im.thumbnail((width, width))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=q, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


def game_html(g):
    key, name, sub, shots, strong, take = g
    m = META[key]
    imgs = "".join(f'<img src="{data_uri(os.path.join(SCREENS, key, f"{n:02d}.jpg"), 960)}" alt="{E(name)} — кадр {i + 1}">' for i, n in enumerate(shots))
