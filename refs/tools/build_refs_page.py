def game_html(g):
    key, name, sub, url, shots, rows, take, skip = g
    imgs = "".join(f'<img loading="lazy" src="{thumb(key, n)}" alt="{E(name)} — скриншот {i+1}">' for i, n in enumerate(shots))
    dl = "".join(f"<dt>{l}</dt><dd>{E(t)}</dd>" for l, t in zip(LABELS, rows))
