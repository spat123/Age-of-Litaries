def write_md():
    out = os.path.join(HERE, "..", "..", "references.md")
    L = ["# Разбор игр-образцов", "",
         "> Собрано 14 ноября 2026 года по настоящим скриншотам со страниц магазинов.",
         "> Страница со скриншотами: `refs/obraztsy.html` (в git не идёт; как собрать — в [`decisions.md`](./decisions.md)).",
         "> Этот файл собирается скриптом `refs/tools/build_refs_page.py` — правь текст там.", "",
         "## Главное", ""]
    for i, (a, b) in enumerate(KEY, 1):
        L.append(f"{i}. **{a}.** {b}")
    L.append("")
    for title, lead, games in GROUPS:
        L += [f"## {title}", "", lead, ""]
        for key, name, sub, url, shots, rows, take, skip in games:
            L += [f"### {name}", "", f"{sub} · [страница в магазине]({url})", ""]
            for l, t in zip(LABELS, rows):
                L.append(f"- **{l}.** {t}")
            L += [f"- **Берём:** {take}", f"- **Не берём:** {skip}", ""]
    L += ["## Итог: что берём", ""]
    L += [f"- **{a}.** {b}" for a, b in TAKE]
    L += ["", "## Итог: что не берём", ""]
    L += [f"- **{a}.** {b}" for a, b in SKIP]
    L.append("")
    open(out, "w", encoding="utf-8").write("\n".join(L))
    print("готово:", os.path.relpath(out))

def thumb(key, n, width=720):
    p = os.path.join(SCREENS, key, f"{n:02d}.jpg")
    im = Image.open(p).convert("RGB")
    im.thumbnail((width, width))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=68, optimize=True)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()

